"""
Контракты поведения через ABC.

Что такое ABC: это "обещание" класса, что он умеет делать. Если класс
наследуется от ABC, но не реализовал её @abstractmethod — Python просто
не даст создать объект такого класса. Так что забыть метод не получится,
ругнётся сразу на этапе new.

Тут два контракта:
  - Printable   — умеет красиво превращать себя в строку (to_string).
  - Comparable  — умеет сравнивать себя с другим объектом (compare_to).

Объект может реализовать оба сразу — это и есть множественная реализация
интерфейсов.
"""

from abc import ABC, abstractmethod


class Printable(ABC):
    """Контракт: я умею выводить себя как красивую строку."""

    @abstractmethod
    def to_string(self) -> str:
        """Вернуть человекочитаемое представление объекта."""
        ...


class Comparable(ABC):
    """Контракт: я умею сравниваться с другим объектом того же рода.

    compare_to(other) должен возвращать:
      < 0  если self < other
      == 0 если равны
      > 0  если self > other
    """

    @abstractmethod
    def compare_to(self, other) -> int:
        """Сравнить себя с other. Семантика классическая: -1 / 0 / +1."""
        ...
