"""
Тут вся проверочная фигня для BankAccount.

Зачем вынесли в отдельный файл:
  - чтоб model.py не превращался в портянку из if-ов,
  - и чтоб одну и ту же проверку не копипастить в конструктор и в сеттеры,
    ибо нефиг.

Каждая функция либо возвращает уже причёсанное значение (типа имя
с большой буквы), либо кидает ValueError с понятным текстом — пусть
вызывающий сам разбирается, чё он туда напихал.
"""


def validate_account_number(value):
    """Номер счёта: непустая строка, чисто цифры, ровно 20 штук.

    20 цифр — это стандартная длина расчётного счёта в России,
    меньше или больше — это уже не номер, а отсебятина.
    """
    if not isinstance(value, str):
        raise ValueError("Номер счёта должен быть строкой")
    # на всякий случай срежем пробелы по краям — мало ли кто что вставит
    value = value.strip()
    if value == "":
        raise ValueError("Номер счёта не может быть пустым")
    if not value.isdigit():
        raise ValueError("Номер счёта должен состоять только из цифр")
    if len(value) != 20:
        raise ValueError("Номер счёта должен содержать ровно 20 цифр")
    return value


def validate_holder_name(value):
    """ФИО владельца: непустая строка из букв, пробелов и дефисов.

    Возвращаем причёсанный вариант через title() — чтоб "иванов иван"
    превратилось в "Иванов Иван", и пользователю не пришлось каждый раз
    самому следить за регистром.
    """
    if not isinstance(value, str):
        raise ValueError("Имя владельца должно быть строкой")
    value = value.strip()
    if value == "":
        raise ValueError("Имя владельца не может быть пустым")
    # пробегаемся по символам: пускаем только буквы, пробелы и дефис.
    # цифры/спецсимволы — мимо, ибо нефиг
    for ch in value:
        if not (ch.isalpha() or ch in (" ", "-")):
            raise ValueError(
                "Имя владельца может содержать только буквы, пробелы и дефисы"
            )
    return value.title()


def validate_balance(value):
    """Баланс: число (int/float), и не меньше нуля.

    bool отсекаем отдельно, потому что в Python True/False — это int
    под капотом, и без этой проверки можно было бы класть на счёт
    "True рублей". Так делать не надо.
    """
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ValueError("Баланс должен быть числом")
    if value < 0:
        raise ValueError("Баланс не может быть отрицательным")
    # сразу гоним в float, чтоб дальше типы не плясали
    return float(value)


def validate_interest_rate(value):
    """Процентная ставка: число от 0 до 100 включительно.

    Меньше 0 — банк сам себе доплачивает, больше 100 — это уже не вклад,
    а финансовая пирамида. И то, и другое нам не надо.
    """
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ValueError("Процентная ставка должна быть числом")
    if value < 0 or value > 100:
        raise ValueError("Процентная ставка должна быть в диапазоне [0; 100]")
    return float(value)
